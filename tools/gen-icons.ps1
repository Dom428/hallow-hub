# Builds src\Icons.g.cs from Font Awesome Free SVGs (only the icons Hallow Hub uses).
#   .\tools\gen-icons.ps1 -FaDir <path to fontawesome-free-*-desktop>
param([Parameter(Mandatory)] [string]$FaDir)
$solid = 'play gamepad magnifying-glass clock chart-line gear plus xmark folder-open rocket sliders check trash-can star arrows-rotate eye-slash eye pen power-off stopwatch trophy fire house list ellipsis circle-play arrow-up-right-from-square volume-high bolt calendar-days hourglass-half table-cells-large grip minus dice tag tags keyboard shield-halved terminal layer-group pen-to-square spinner download hard-drive broom filter image bell mug-hot file-csv mobile-screen temperature-half memory microchip tv expand thumbtack note-sticky clock-rotate-left box-open share-nodes heart-pulse paper-plane floppy-disk film rotate-left arrow-down-wide-short newspaper chart-column file-zipper cart-shopping file-import file-export circle-info compact-disc flag-checkered bookmark people-group globe magnet envelope wallet location-dot gauge-high key hand-holding-heart lock lock-open pause circle-check triangle-exclamation circle-xmark stethoscope camera display moon file-lines' -split ' '
$brands = @('steam', 'battle-net', 'windows', 'discord', 'xbox', 'microsoft')
$sb = New-Object Text.StringBuilder
[void]$sb.AppendLine('// Generated by tools\gen-icons.ps1 - do not edit.')
[void]$sb.AppendLine('// Icons: Font Awesome Free 7.3.1 by Fonticons, Inc. - https://fontawesome.com - licensed CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/).')
[void]$sb.AppendLine('using System.Collections.Generic;')
[void]$sb.AppendLine('namespace HallowHub')
[void]$sb.AppendLine('{')
[void]$sb.AppendLine('    public static partial class Icons')
[void]$sb.AppendLine('    {')
[void]$sb.AppendLine('        // name -> SVG path data (Font Awesome viewBox height is 512)')
[void]$sb.AppendLine('        static readonly Dictionary<string, string> Data = new Dictionary<string, string> {')
foreach ($set in @(@{ dir = 'solid'; names = $solid }, @{ dir = 'brands'; names = $brands })) {
    foreach ($n in $set.names) {
        $svg = Get-Content (Join-Path $FaDir "svgs\$($set.dir)\$n.svg") -Raw
        $vb = [regex]::Match($svg, 'viewBox="0 0 (\d+) (\d+)"')
        $d = [regex]::Match($svg, ' d="([^"]+)"').Groups[1].Value
        # keep the true width: prepend an invisible move so the geometry bounds span the whole viewBox
        $w = $vb.Groups[1].Value; $h = $vb.Groups[2].Value; $path = "M0 0L0 0M$w ${h}L$w $h" + $d
        [void]$sb.AppendLine("            { `"$n`", `"$path`" },")
    }
}
# v2.26: hand-drawn shapes (not Font Awesome) - copied from Hallow Paint's Icons.g.cs
$hand = [ordered]@{ 'tool-brush' = 'M0 0L0 0M512 512L512 512M440 40L472 72L300 284L252 236ZM236 252L284 300C284 372 228 432 128 448C96 452 64 452 48 444C96 404 96 364 112 324C128 276 180 252 236 252Z' }
[void]$sb.AppendLine("            // hand-drawn for the Hallow apps (copied from Hallow Paint's Icons.g.cs) - v2.26: Hallow Paint's card")
foreach ($k in $hand.Keys) { [void]$sb.AppendLine("            { `"$k`", `"$($hand[$k])`" },") }
[void]$sb.AppendLine('        };')
[void]$sb.AppendLine('    }')
[void]$sb.AppendLine('}')
$out = Join-Path $PSScriptRoot '..\src\Icons.g.cs'
[IO.File]::WriteAllText($out, $sb.ToString(), (New-Object Text.UTF8Encoding($false)))
"Wrote $out ($($solid.Count + $brands.Count) icons)"

